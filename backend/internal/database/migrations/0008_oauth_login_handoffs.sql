CREATE TABLE IF NOT EXISTS public.oauth_login_handoffs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_digest character varying NOT NULL,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    expires_at timestamp without time zone NOT NULL,
    used_at timestamp without time zone,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS index_oauth_login_handoffs_on_code_digest
    ON public.oauth_login_handoffs USING btree (code_digest);

CREATE INDEX IF NOT EXISTS index_oauth_login_handoffs_on_user_id
    ON public.oauth_login_handoffs USING btree (user_id);

CREATE INDEX IF NOT EXISTS index_oauth_login_handoffs_on_expires_at
    ON public.oauth_login_handoffs USING btree (expires_at);
